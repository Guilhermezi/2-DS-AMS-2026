export function isNumberWord(word) {
  return /^\d+([.,]\d+)?%?$/.test(word)
}

export function normalizeWord(word) {
  return word
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
}